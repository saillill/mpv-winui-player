def gen_section_glue(rows: list[dict]) -> str:
    """The registration fragment BuildSettings needs.

    The page resolves a row's section from `sectionMap` and fails loudly on a
    row that is in neither the map nor the Shortcut: escape hatch, so a
    generated row has to appear here rather than carrying its section inline.
    The whole thing is one method taking the three collections, because all
    three are keyed by the same section constants and are read together.
    """
    by_folder: dict[str, list[dict]] = {}
    for r in rows:
        by_folder.setdefault(folder_for(r), []).append(r)

    # Folder order: the eight coherent mpv groups in their declared order,
    # then the General themes in the order GENERAL_THEMES lists them. Encoding
    # and Terminal lead, because those are the two a person is most likely to
    # want and least likely to find by guessing.
    def sort_key(sec: str) -> tuple[int, int]:
        if not sec.startswith("SectionGenGeneral"):
            return (0, list(GROUP_TO_SECTION.values()).index(sec))
        theme = sec[len("SectionGenGeneral"):]
        order = [k for k, _c, _d, _i, _p in GENERAL_THEMES] + ["其他"]
        return (1, order.index(theme) if theme in order else len(order))

    folders = sorted(by_folder, key=sort_key)

    lines = [
        BANNER,
        "using System;\nusing System.Collections.Generic;\n",
        "namespace mpv_winui.Modules.Settings\n{",
        "    public sealed partial class SettingsPage\n    {",
        "        /// <summary>",
        "        /// Registration for the schema-generated rows.",
        "        ///",
        "        /// These fragments are the whole reason a generated row is",
        "        /// visible at all: the page reads sections from a map (not from",
        "        /// the Option), orders them from a second map, and decides",
        "        /// folding from a third. All three are written here so adding a",
        "        /// folder means regenerating, not remembering three places.",
        "        ///",
        "        /// The generated folders all fold. They hold the options nobody",
        "        /// wrote a curated row for, which is the same test the",
        "        /// hand-written advanced sections pass -- and 548 rows on a",
        "        /// category overview is the wall of text the fold exists to",
        "        /// prevent.",
        "        /// </summary>",
        "        private static void RegisterGeneratedSections(",
        "            IDictionary<string, string> sectionMap,",
        "            IDictionary<string, int> sectionOrder,",
        "            ISet<string> advancedSections)",
        "        {",
        "            var lang = AppContext.AppLang;",
        "",
    ]

    for folder in folders:
        group, cap, desc, _icon = folder_meta(folder)
        rows_here = by_folder[folder]
        # Order 1000+ keeps generated folders after every hand-written one, and
        # the index keeps them in this file's order rather than alphabetical:
        # Encoding above Terminal above Platform is a judgement, and an
        # alphabetical sort would silently undo it.
        lines.append(f"            // {cap} -- {len(rows_here)} row(s), from mpv's \"{group}\"")
        lines.append(f"            sectionOrder[lang.{folder}] = {1000 + folders.index(folder)};")
        lines.append(f"            advancedSections.Add(lang.{folder});")
        lines.append("")
        for r in sorted(rows_here, key=lambda x: x["name"]):
            lines.append(
                f"            sectionMap[nameof(AppContext.AppSetting.{r['prop']})] = lang.{folder};")
        lines.append("")

    lines += ["        }", "    }", "}", ""]
    return "\n".join(lines)


def gen_section_captions(rows: list[dict]) -> str:
    """AppLang caption + description properties, one pair per generated folder.

    The page keys sections by their localized caption, so a generated folder
    needs a caption property exactly like a hand-written one. The Chinese text
    is written here rather than derived from the schema because the schema's
    group names are English and describe mpv's own grouping, not this
    window's wording -- and the General themes are a split mpv does not have
    at all.
    """
    folders = sorted({folder_for(r) for r in rows})

    lines = [BANNER, "namespace mpv_winui.Modules.Language\n{",
             "    public partial class AppLang\n    {"]
    for folder in folders:
        _group, cap, desc, _icon = folder_meta(folder)
        lines.append(f'        public string {folder} {{ get; set; }} = "{cap}";')
        lines.append(f'        public string SectionDesc{folder[len("Section"):]} {{ get; set; }} = "{desc}";')
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def gen_labels(rows: list[dict]) -> dict:
    """Label + description text per generated row.

    English, taken from the schema. The label is the option's own name, which is
    the only name it has and the one a reader would type into mpv.conf.

    The description is the schema's type line, and the manual link is NOT
    appended to it. A URL under a setting asks the reader to leave the window to
    find out what the row does, and it is the same page every time.
    """
    def _no_link(text: str) -> str:
        # A few schema lines carry their own URL. Same reason as the link field:
        # a row's help does not need to send the reader to a web page.
        return re.sub(r"\s*[（(]?\s*https?://\S+\s*[)）]?", "", text or "").strip()

    # The schema's own `desc` is a type line -- "Float; Range 0 to 6; Default: 0"
    # -- which says what the row accepts and nothing about what it does. The
    # manual describes each option in a sentence, and that is what a reader needs
    # first, so it wins when it is available; the type line remains the fallback
    # for the options the manual no longer documents.
    manual = {}
    if MANUAL_DESC.exists():
        manual = json.loads(MANUAL_DESC.read_text(encoding="utf-8"))

    # Titles a person wrote, where there is one. The option name is always
    # technically right, but "ad-lavc-ac3drc" is not a name a reader can scan;
    # rows are moved in a section at a time, so this stays a partial map.
    hand = {}
    if HAND_LABELS.exists():
        hand = {k: v for k, v in json.loads(HAND_LABELS.read_text(encoding="utf-8")).items()
                if not k.startswith("_")}

    labels = {}
    for r in rows:
        title = hand.get(r["name"], {}).get("en") or r["name"]
        labels[f"SchemaLabel_{r['prop']}"] = _no_link(title)
        labels[f"SchemaDesc_{r['prop']}"] = _no_link(manual.get(r["name"]) or r["desc"])
    return labels


def gen_applang_partial(rows: list[dict], labels: dict) -> str:
    """AppLang properties for the generated labels.

    Without these `lang.SchemaLabel_Mpv_X` does not compile: AppLang is a
    plain class with one property per string, not a dictionary lookup.

    The values come from `gen_labels`, NOT from the row's own name and type
    line. Those C# defaults are what the UI actually reads for English: only
    zh-CN carries Schema* keys in Languages/, so every other language falls
    back here. Emitting the raw option name and the schema's type line made
    schema-labels.en.json -- which nothing loads -- the only place the
    hand-written titles and the manual prose existed, so they never reached
    a window. One label map, two writers.
    """
    lines = [BANNER, "namespace mpv_winui.Modules.Language\n{",
             "    public partial class AppLang\n    {"]
    for r in sorted(rows, key=lambda x: x["prop"]):
        label = labels[f"SchemaLabel_{r['prop']}"]
        desc = labels[f"SchemaDesc_{r['prop']}"]
        lines.append(f'        public string SchemaLabel_{r["prop"]} {{ get; set; }} = {_cs_string(label)};')
        lines.append(f'        public string SchemaDesc_{r["prop"]} {{ get; set; }} = {_cs_string(desc)};')
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def gen_sections(rows: list[dict]) -> str:
    """The section catalogue fragment: the entries SettingsSections.All needs.

    Deliberately NOT a method that returns the list. It used to be
    `GeneratedSections()`, an IEnumerable the page never called -- the real
    list is `SettingsSections.All`, and the icons there are codepoints while
    the method emitted names like "IconVideo" that resolve to nothing. So it
    looked like the registry, was the obvious place to add a folder, and
    wiring a folder into it did nothing at all.

    What is emitted now is a `// ---- schema-generated sections ----` block to
    paste into SettingsSections.All, carrying the exact `new(...)` lines with
    fresh codepoints. The generator cannot patch that file itself (it mixes
    hand-written and generated entries in one array, and rewriting it would
    take the hand-written half with it), so it prints the block and a
    check-sections.py run confirms both halves are present.
    """
    folders = sorted({folder_for(r) for r in rows})
    plain = list(GROUP_TO_SECTION.values())
    order = [k for k, _c, _d, _i, _p in GENERAL_THEMES] + ["其他"]

    def key(sec: str) -> tuple[int, int]:
        if sec in plain:
            return (0, plain.index(sec))
        theme = sec[len("SectionGenGeneral"):]
        return (1, order.index(theme) if theme in order else len(order))

    used = re.findall(r'\\u([0-9A-Fa-f]{4})',
                      (SETTINGS / "Layout" / "SettingsSections.cs").read_text(encoding="utf-8-sig"))
    taken = {int(u, 16) for u in used}
    pool = [c for c in range(0xE700, 0xE760) if c not in taken]

    lines = [BANNER,
             "// Paste the entries below into SettingsSections.All, replacing any of the",
             "// same name. That array is the list the page actually reads; there is no",
             "// registry method to call.",
             "namespace mpv_winui.Modules.Settings\n{",
             "    public sealed partial class SettingsPage\n    {",
             "        // ---- schema-generated sections ----"]
    for i, folder in enumerate(sorted(folders, key=key)):
        _group, cap, desc, _icon = folder_meta(folder)
        glyph = pool[i % len(pool)]
        lines.append(f"        // {cap} -- {desc}")
        lines.append(
            f'        new("{folder}", "\\u{glyph:04X}", '
            f"l => l.{folder}, l => l.SectionDesc{folder[len('Section'):]}),")
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows, skipped = load_generated()

    print(f"schema entries   : {len(json.loads(SCHEMA.read_text(encoding='utf-8-sig')))}")
    print(f"  deprecated     : {skipped['deprecated']}")
    print(f"  not applicable : {skipped['not-applicable']}")
    print(f"  hand-written   : {skipped['hand-written']}")
    print(f"  generated here : {len(rows)}")
    print()
    print("by group:")
    for g, n in Counter(r["group"] for r in rows).most_common():
        print(f"  {n:4d}  {g:22s} -> {GROUP_TO_CATEGORY.get(g, '?')}")
    print()
    print("by folder:")
    for folder, n in Counter(folder_for(r) for r in rows).most_common():
        _group, cap, _desc, icon = folder_meta(folder)
        print(f"  {n:4d}  {cap:14s} ({folder})  [{icon}]")
    unclassified = [r["name"] for r in rows if folder_for(r) == "SectionGenGeneral其他"]
    if unclassified:
        print()
        print(f"  !! {len(unclassified)} option(s) matched no General theme and fell "
              f"into 其他 -- give each one a pattern in GENERAL_THEMES:")
        for name in unclassified:
            print(f"       {name}")
    print()
    print("by control type:")
    for t, n in Counter(r["cs"] for r in rows).most_common():
        print(f"  {n:4d}  {t}")
    no_enum_strings = sum(1 for r in rows if r["cs"] == "string" and not r["meta"].get("enum"))
    print(f"  ({no_enum_strings} of the strings are free text; "
          f"{sum(1 for r in rows if r['meta'].get('enum'))} have an enum)")

    labels = gen_labels(rows)
    targets = {
        SETTINGS / "AppSettings.Gen.cs": gen_appsettings(rows),
        SETTINGS / "MpvSettings.Gen.cs": gen_names(rows),
        SETTINGS / "SettingsPage.Options.Gen.cs": gen_options(rows),
        SETTINGS / "SettingsPage.Sections.Gen.cs": gen_section_glue(rows),
        APP / "Modules" / "Language" / "AppLang.Gen.cs": gen_applang_partial(rows, labels),
        APP / "Modules" / "Language" / "AppLang.Sections.Gen.cs": gen_section_captions(rows),
        GEN_LABELS: json.dumps(labels, ensure_ascii=False, indent=2) + "\n",
    }

    if args.check:
        stale = [p for p, text in targets.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"STALE: {p.relative_to(REPO)}")
        print("OK: generated files up to date" if not stale else f"FAIL: {len(stale)} stale")
        return 1 if stale else 0

    if args.dry_run:
        for p, text in targets.items():
            print(f"  would write {p.relative_to(REPO)}  ({len(text.splitlines())} lines)")
        print("\n--dry-run: nothing written")
        return 0

    for p, text in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        # LF and no BOM, matching the rest of the generated/tooling output.
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(REPO)}  ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
