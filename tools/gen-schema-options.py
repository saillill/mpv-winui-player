#!/usr/bin/env python3
"""Generate the settings-page rows for every mpv option the page does not
already carry, from the bundled schema.

Why generate instead of hand-write
----------------------------------
`SettingsPage.Options.*.cs` holds 317 hand-written rows. The bundled schema
(`MpvConfOptions/mpv-options.json`, produced by `mpv --list-options`) has
820 entries, of which 263 are already wired up -- leaving 549 with no row
and no AppSettings property. Hand-writing 549 rows x (property + command
case + name map entry + Option literal) is roughly 12k lines of largely
mechanical code that would drift from the schema on the next mpv bump.

So the schema drives it:

    mpv-options.json
        |
        +-- AppSettings.Gen.cs        549 properties, typed from `values`
        +-- MpvSettings.Gen.cs        549 name-map entries + value grammar
        +-- SettingsPage.Options.Gen.cs  549 Option literals
        +-- MpvConfOptions/schema-labels.en.json  label + description text

Every generated file carries a "do not edit" banner and is rewritten whole,
so the diff after an mpv upgrade is exactly the options that changed.

Key stability
-------------
The AppSettings property name is what keys everything else (the name map,
mpv.conf ownership, the schema-version migration), so it is derived from
the mpv option name in a way that cannot collide with the hand-written set
and is stable across regenerations: `mpv_<name with dashes as underscores>`.

Value grammar
-------------
mpv's config syntax and its command syntax accept the same values, so the
generated command is `set <name> <literal>` with the literal quoted only
when the schema says the value is a string that is not a bare token. That
keeps one source of truth: the schema declares the type, the generator
writes the literal, nothing restates the grammar by hand.

Coverage exclusions
-------------------
Skipped by design, and counted in the run report:
  * `deprecated: true` entries (8) -- mpv itself says do not use
  * names already wired up by hand (263) -- the hand-written row wins,
    because it has a real Chinese label, a chosen control and warnings
  * names that need a widget this generator cannot infer: array/list values
    with no enum (the 54 `array` + 45 `raw` entries) are emitted as plain
    string rows with a `;` separator, which is what mpv accepts on the
    command line, rather than guessing at a dedicated editor

Usage:
  python tools/gen-schema-options.py            # write
  python tools/gen-schema-options.py --dry-run  # report only
  python tools/gen-schema-options.py --check    # fail if files are stale
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
APP = REPO / "mpv-winui" / "mpv-winui"
SCHEMA = APP / "MpvConfOptions" / "mpv-options.json"
SETTINGS = APP / "Modules" / "Settings"
LANGDIR = APP / "Languages"
# The English label/description source, kept OUT of Languages/ on purpose:
# that directory is scanned by check-localization.py as "one file per UI
# language", and every file in it must carry all 1000+ AppLang properties.
# This table carries only the schema labels, so living there made the check
# report it as a language pack missing hundreds of keys. It still ships, it
# is just not a language.
GEN_LABELS = APP / "MpvConfOptions" / "schema-labels.en.json"

BANNER = """// <auto-generated>
//     Generated by tools/gen-schema-options.py from MpvConfOptions/mpv-options.json.
//     Do not edit by hand: the next run overwrites the whole file.
//     To change what appears here, change the generator or the schema.
// </auto-generated>
"""

# Group -> which existing settings category the rows land under. The schema's
# own grouping is coarser than the page's, so this is a translation, not a
# copy. Anything unmapped falls into General, which is where mpv's own
# "everything else" lives too.
GROUP_TO_CATEGORY = {
    "Video & rendering": "SettingsCategoryVideo",
    "Colour & HDR": "SettingsCategoryVideo",
    "Subtitles": "SettingsCategorySubtitles",
    "OSD": "SettingsCategoryOsd",
    "Audio": "SettingsCategoryAudio",
    "Streaming & cache": "SettingsCategoryNetwork",
    "Tracks": "SettingsCategoryPlayback",
    "Player & window": "SettingsCategoryWindow",
    "General": "SettingsCategoryProgram",
}

# Second-level folder each generated row lands in, per group. One folder per
# group keeps 205 Video rows from becoming a 205-row flat list on the
# category overview.
GROUP_TO_SECTION = {
    "Video & rendering": "SectionGenVideoRendering",
    "Colour & HDR": "SectionGenColourHdr",
    "Subtitles": "SectionGenSubtitles",
    "OSD": "SectionGenOsd",
    "Audio": "SectionGenAudio",
    "Streaming & cache": "SectionGenStreaming",
    "Tracks": "SectionGenTracks",
    "Player & window": "SectionGenPlayerWindow",
    "General": "SectionGenGeneral",
}

# Icons reused from the existing set. A generated row must not introduce a
# new glyph: check-sections.py asserts every section has a distinct icon,
# and inventing 9 more risks a collision for no benefit.
GROUP_TO_ICON = {
    "Video & rendering": "IconVideo",
    "Colour & HDR": "IconColor",
    "Subtitles": "IconSubtitles",
    "OSD": "IconOsd",
    "Audio": "IconAudio",
    "Streaming & cache": "IconNetwork",
    "Tracks": "IconPlaylist",
    "Player & window": "IconWindow",
    "General": "IconSettings",
}

SKIP_TYPES = {"array", "raw"}   # still emitted, but as plain string rows


def prop_name(opt: str) -> str:
    """AppSettings property name for an mpv option name.

    Prefixed so it can never collide with the hand-written properties, and
    with dashes folded to underscores because that is the only character
    mpv option names use that C# identifiers cannot.
    """
    return "Mpv_" + opt.replace("-", "_")


def classify(entry: dict) -> tuple[str, dict]:
    """(cs_type, meta) for one schema entry.

    mpv allows several accepted value shapes for one option; the first
    branch that can hold a value is the one used, because that branch is
    what mpv will parse first too.
    """
    for v in entry["values"]:
        t = v["type"]
        if t == "bool":
            return "bool", {"default": entry.get("default") == "yes"}
        if t == "int":
            return "int", {
                "min": v.get("minimum"),
                "max": v.get("maximum"),
                "default": _as_int(entry.get("default")),
            }
        if t == "float":
            return "double", {
                "min": v.get("minimum"),
                "max": v.get("maximum"),
                "default": _as_float(entry.get("default")),
            }
        if t == "string":
            enum = v.get("enum") or []
            if enum:
                return "string", {
                    "enum": [e.get("value", "") for e in enum],
                    "default": _as_str(entry.get("default")),
                }
            return "string", {"default": _as_str(entry.get("default"))}
        if t in SKIP_TYPES:
            return "string", {"default": _as_str(entry.get("default"))}
    return "string", {"default": _as_str(entry.get("default"))}


def _as_int(raw):
    try:
        return int(float(raw))
    except (TypeError, ValueError):
        return 0


def _as_float(raw):
    try:
        return float(raw)
    except (TypeError, ValueError):
        return 0.0


def _as_str(raw) -> str:
    return "" if raw is None else str(raw)


def load_generated() -> list[dict]:
    """Every schema entry this generator is responsible for."""
    schema = json.loads(SCHEMA.read_text(encoding="utf-8-sig"))

    # Names the hand-written rows already own. Read from the source rather
    # than a checked-in list so adding a hand-written row automatically
    # drops its generated twin instead of duplicating it.
    wired = set()
    mpvsettings = (SETTINGS / "MpvSettings.cs").read_text(encoding="utf-8-sig")
    for name in re.findall(r'\[\s*(?:nameof\(AppSettings\.)?\w+\s*\]\s*=\s*"([a-z0-9\-]+)"', mpvsettings):
        wired.add(name)
    for name in re.findall(r'\bset ([a-z][a-z0-9\-]*)\s', mpvsettings):
        wired.add(name)

    out, skipped = [], Counter()
    for entry in schema:
        name = entry["name"]
        if entry.get("deprecated"):
            skipped["deprecated"] += 1
            continue
        if name in wired:
            skipped["hand-written"] += 1
            continue
        cs, meta = classify(entry)
        out.append({
            "name": name,
            "prop": prop_name(name),
            "group": entry.get("group", "General"),
            "desc": entry.get("desc", ""),
            "link": entry.get("link", ""),
            "cs": cs,
            "meta": meta,
        })
    return out, skipped


def gen_appsettings(rows: list[dict]) -> str:
    """AppSettings properties, grouped by category for a readable diff."""
    by_group: dict[str, list[dict]] = {}
    for r in rows:
        by_group.setdefault(r["group"], []).append(r)

    parts = [BANNER, "namespace mpv_winui.Modules.Settings\n{\n    public partial class AppSettings\n    {"]
    for group in sorted(by_group):
        parts.append(f"        // ---- {group} ----\n")
        for r in sorted(by_group[group], key=lambda x: x["name"]):
            cs, meta = r["cs"], r["meta"]
            if cs == "bool":
                lit = "true" if meta["default"] else "false"
            elif cs == "string":
                lit = '"' + meta["default"].replace('\\', '\\\\').replace('"', '\\"') + '"'
            elif cs == "int":
                lit = str(meta["default"])
            else:
                lit = repr(float(meta["default"]))
            parts.append(
                f"        public {cs} {r['prop']}\n"
                f"        {{\n"
                f"            get => _dataSetting.GetValue(nameof({r['prop']}), {lit});\n"
                f"            set => _dataSetting.SetValue(nameof({r['prop']}), value);\n"
                f"        }}\n"
            )
    parts.append("    }\n}\n")
    return "\n".join(parts)


def gen_names(rows: list[dict]) -> str:
    """The name-map fragment: property name -> mpv option name.

    Kept in its own partial so the hand-written dictionary in MpvSettings.cs
    stays readable, and so `git diff` after an mpv bump shows only the
    options that appeared or disappeared.
    """
    lines = [BANNER, "using System;\nusing System.Collections.Generic;\n",
             "namespace mpv_winui.Modules.Settings\n{",
             "    public static partial class MpvSettings\n    {",
             "        /// <summary>Name map for the schema-generated rows.</summary>",
             "        private static readonly Dictionary<string, string> GeneratedOptionNames = new(StringComparer.Ordinal)",
             "        {"]
    for r in sorted(rows, key=lambda x: x["name"]):
        lines.append(f'            [nameof(AppSettings.{r["prop"]})] = "{r["name"]}",')
    lines += ["        };", "    }", "}", ""]
    return "\n".join(lines)


def gen_options(rows: list[dict]) -> str:
    """The Option literals, plus the section/icon registration they need."""
    by_group: dict[str, list[dict]] = {}
    for r in rows:
        by_group.setdefault(r["group"], []).append(r)

    out = [BANNER, "using System;\nusing System.Collections.Generic;\nusing System.Linq;",
           "using mpv_winui.Modules.Settings.Controls;\n",
           "namespace mpv_winui.Modules.Settings;\n",
           "public sealed partial class SettingsPage\n{",
           "    /// <summary>",
           "    /// One row per mpv option the hand-written page does not cover.",
           "    ///",
           "    /// These are all advanced by construction: they are the options",
           "    /// nobody wrote a curated row for. Every one lands behind the",
           "    /// generated section cards rather than on a category overview,",
           "    /// which is the same rule the hand-written advanced rows follow.",
           "    /// </summary>",
           "    private List<Option> BuildGeneratedOptions()",
           "    {",
           "        var lang = AppContext.AppLang;",
           "        var list = new List<Option>();\n"]

    for group in sorted(by_group):
        cat = GROUP_TO_CATEGORY[group]
        sec = GROUP_TO_SECTION[group]
        icon = GROUP_TO_ICON[group]
        gvar = "cat" + re.sub(r"\W", "", group.title())
        svar = "sec" + re.sub(r"\W", "", group.title())
        out.append(f"        // ---- {group} ({len(by_group[group])} rows) ----")
        out.append(f"        var {gvar} = AppContext.AppLang.{cat};")
        out.append(f"        var {svar} = AppContext.AppLang.{sec};")
        for r in sorted(by_group[group], key=lambda x: x["name"]):
            out.append(_option_literal(r, gvar, svar, icon))
        out.append("")

    out += ["        return list;", "    }", "}", ""]
    return "\n".join(out)


def _placeholder(desc: str) -> str:
    """The hint text for a free-text row, from the schema's own desc.

    mpv's desc strings are a fixed grammar -- "String", "ByteSize; Default:
    1.000 MiB", "One of: auto; or a number" -- where everything before the
    first "; Default:" names the value's shape. That prefix is exactly the
    hint a user needs, and it is already translated in spirit: it is mpv's
    own vocabulary, the same words the manual uses.
    """
    head = desc.split("; Default:")[0].strip()
    head = head.split("; or a number")[0].strip()
    return "" if head in {"String", ""} else head


def _cs_string(s: str) -> str:
    """A C# string literal for `s`, escaping what the compiler needs."""
    body = (s.replace("\\", "\\\\")
             .replace('"', '\\"')
             .replace("\r", "\\r")
             .replace("\n", "\\n"))
    return f'"{body}"'


def _option_literal(r: dict, gvar: str, svar: str, icon: str) -> str:
    cs, meta = r["cs"], r["meta"]
    label_key = f"SchemaLabel_{r['prop']}"
    desc_key = f"SchemaDesc_{r['prop']}"
    name = r["name"]
    prop = r["prop"]
    extra: list[str] = []

    if cs == "bool":
        typ = "OptionType.Boolean"
        getter = f"() => AppContext.AppSetting.{prop}"
        setter = f"v => ApplyMpv(nameof(AppContext.AppSetting.{prop}), AppContext.AppSetting.{prop} = (bool)v!)"
    elif cs == "int":
        typ = "OptionType.Integer"
        extra = []
        if meta.get("min") is not None:
            extra.append(f"Min = {(int(meta['min']) if float(meta['min']).is_integer() else meta['min'])}")
        if meta.get("max") is not None:
            extra.append(f"Max = {(int(meta['max']) if float(meta['max']).is_integer() else meta['max'])}")
        getter = f"() => (double)AppContext.AppSetting.{prop}"
        setter = (f"v => ApplyMpv(nameof(AppContext.AppSetting.{prop}), "
                  f"AppContext.AppSetting.{prop} = Convert.ToInt32(v))")
    elif cs == "double":
        typ = "OptionType.Double"
        extra = []
        if meta.get("min") is not None:
            extra.append(f"Min = {meta['min']}")
        if meta.get("max") is not None:
            extra.append(f"Max = {meta['max']}")
        getter = f"() => AppContext.AppSetting.{prop}"
        setter = f"v => ApplyMpv(nameof(AppContext.AppSetting.{prop}), AppContext.AppSetting.{prop} = (double)v!)"
    else:
        enum = meta.get("enum")
        if enum:
            typ = "OptionType.StringList"
            choices = "\n".join(
                f'                        new OptionChoice("{e.replace(chr(92), chr(92)*2).replace(chr(34), chr(92)+chr(34))}", "{e}"),'
                for e in enum
            )
            extra = ["Choices =\n                    [\n" + choices + "\n                    ]"]
        else:
            typ = "OptionType.String"
            # The schema's own syntax string is the one thing that can tell a
            # user what this box wants: these options carry no hand-written
            # help, and the desc beside the field says what mpv calls the
            # value, not what shape it takes. A blank free-text field that
            # accepts "1.000 MiB" while the user types "1024" is the failure
            # this prevents, and the schema already knows the answer.
            # check-placeholders.py requires a hint here for the same reason.
            extra = ["AllowEmpty = true"]
            syntax = _placeholder(r["desc"])
            if syntax:
                extra.append(f'Placeholder = {_cs_string(syntax)}')
        getter = f"() => AppContext.AppSetting.{prop}"
        setter = f"v => ApplyMpv(nameof(AppContext.AppSetting.{prop}), AppContext.AppSetting.{prop} = (string)v!)"

    # The literal is wrapped in list.Add(...) here rather than at the call
    # site so a row cannot be emitted and then silently dropped: an
    # expression statement of `new Option { ... }` compiles away to
    # nothing, which is exactly how the first generation produced 549
    # orphans that never reached the page.
    lines = [
        "            list.Add(new Option",
        "            {",
        f"                Key = nameof(AppContext.AppSetting.{prop}),",
        f"                Label = lang.{label_key},",
        f"                Category = {gvar},",
        f"                Section = {svar},",
        f"                Description = lang.{desc_key},",
        f"                Type = {typ},",
    ]
    for e in extra:
        lines.append(f"                {e},")
    lines += [
        # No AdvancedSection. Whether a row sits behind its section's card is a
        # single decision the page makes for the whole section, and it makes it
        # after sectionMap has resolved Section -- so a flag baked in here could
        # only ever be a second source of truth, one the page then had to
        # remember to overwrite in both directions. It is not emitted at all
        # rather than emitted as false, so nobody can mistake it for an input.
        f"                Getter = {getter},",
        f"                Setter = {setter},",
        "            });",
    ]
    return "\n".join(lines)


def gen_section_glue(rows: list[dict]) -> str:
    """The registration fragment BuildSettings needs.

    The page resolves a row's section from `sectionMap` and fails loudly on a
    row that is in neither the map nor the Shortcut: escape hatch, so a
    generated row has to appear here rather than carrying its section inline.
    The whole thing is one method taking the three collections, because all
    three are keyed by the same section constants and are read together.
    """
    by_group: dict[str, list[dict]] = {}
    for r in rows:
        by_group.setdefault(r["group"], []).append(r)
    groups = sorted(by_group)

    lines = [
        BANNER,
        "using System;\nusing System.Collections.Generic;\n",
        "namespace mpv_winui.Modules.Settings\n{",
        "    public sealed partial class SettingsPage\n    {",
        "        /// <summary>",
        "        /// Registration for the schema-generated rows.",
        "        ///",
        "        /// These fragments are the whole reason a generated row is",
        "        /// visible at all: the page reads sections from a map (not from",
        "        /// the Option), orders them from a second map, and decides",
        "        /// folding from a third. All three are written here so adding a",
        "        /// group means regenerating, not remembering three places.",
        "        ///",
        "        /// The generated sections all fold. They hold the options nobody",
        "        /// wrote a curated row for, which is the same test the",
        "        /// hand-written advanced sections pass -- and 549 rows on a",
        "        /// category overview is the wall of text the fold exists to",
        "        /// prevent.",
        "        /// </summary>",
        "        private static void RegisterGeneratedSections(",
        "            IDictionary<string, string> sectionMap,",
        "            IDictionary<string, int> sectionOrder,",
        "            ISet<string> advancedSections)",
        "        {",
        "            var lang = AppContext.AppLang;",
        "",
    ]

    for i, g in enumerate(groups):
        sec = GROUP_TO_SECTION[g]
        lines.append(f"            // {g} -> {GROUP_TO_CATEGORY[g]}")
        lines.append(f"            sectionOrder[lang.{sec}] = {100 + i};")
        lines.append(f"            advancedSections.Add(lang.{sec});")
        lines.append("")
        for r in sorted(by_group[g], key=lambda x: x["name"]):
            lines.append(
                f"            sectionMap[nameof(AppContext.AppSetting.{r['prop']})] = lang.{sec};")
        lines.append("")

    lines += ["        }", "    }", "}", ""]
    return "\n".join(lines)


def gen_section_captions(rows: list[dict]) -> str:
    """AppLang caption + description properties, one pair per generated section.

    The page keys sections by their localized caption, so a generated section
    needs a caption property exactly like a hand-written one. The Chinese text
    is written here rather than derived from the schema because the schema's
    group names are English and describe mpv's own grouping, not this
    window's wording.
    """
    captions = {
        "Video & rendering": ("视频渲染选项", "视频、缩放、滤镜等全部选项"),
        "Colour & HDR": ("色彩与 HDR 选项", "色彩管理、色调映射等全部选项"),
        "Subtitles": ("字幕选项", "全部字幕相关选项"),
        "OSD": ("OSD 选项", "全部 OSD 相关选项"),
        "Audio": ("音频选项", "全部音频相关选项"),
        "Streaming & cache": ("流媒体与缓存选项", "网络、缓存、解复用等全部选项"),
        "Tracks": ("轨道选项", "音视频轨道选择的全部选项"),
        "Player & window": ("播放器与窗口选项", "播放器行为与窗口的全部选项"),
        "General": ("常规选项", "其余全部 mpv 选项"),
    }

    lines = [BANNER, "namespace mpv_winui.Modules.Language\n{",
             "    public partial class AppLang\n    {"]
    for g in sorted({r["group"] for r in rows}):
        sec = GROUP_TO_SECTION[g]
        cap, desc = captions.get(g, (g, g))
        lines.append(f'        public string {sec} {{ get; set; }} = "{cap}";')
        lines.append(f'        public string SectionDesc{sec[len("Section"):]} {{ get; set; }} = "{desc}";')
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def gen_labels(rows: list[dict]) -> dict:
    """Label + description text per generated row.

    English first, taken from the schema, with the mpv manual link kept in
    the description so the row is still actionable without a translation.
    The file is separate from the other language files so a later pass can
    replace it with real translations without touching this generator.
    """
    labels = {}
    for r in rows:
        labels[f"SchemaLabel_{r['prop']}"] = r["name"]
        desc = r["desc"]
        if r["link"]:
            desc = f"{desc}  ({r['link']})" if desc else r["link"]
        labels[f"SchemaDesc_{r['prop']}"] = desc
    return labels


def gen_applang_partial(rows: list[dict]) -> str:
    """AppLang properties for the generated labels.

    Without these `lang.SchemaLabel_Mpv_X` does not compile: AppLang is a
    plain class with one property per string, not a dictionary lookup.
    """
    lines = [BANNER, "namespace mpv_winui.Modules.Language\n{",
             "    public partial class AppLang\n    {"]
    for r in sorted(rows, key=lambda x: x["prop"]):
        lines.append(f'        public string SchemaLabel_{r["prop"]} {{ get; set; }} = "{r["name"]}";')
        desc = r["desc"].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        public string SchemaDesc_{r["prop"]} {{ get; set; }} = "{desc}";')
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def gen_sections(rows: list[dict]) -> str:
    """Section caption + description AppLang properties and their registration.

    A generated section needs three things the existing sections already
    have: a caption property, a description property, and an entry in the
    page's section list with an icon. All three are emitted here.
    """
    groups = sorted({r["group"] for r in rows})
    lines = [BANNER, "using System.Collections.Generic;\n",
             "namespace mpv_winui.Modules.Settings\n{",
             "    public sealed partial class SettingsPage\n    {",
             "        /// <summary>",
             "        /// Second-level folders for the schema-generated rows.",
             "        ///",
             "        /// One per mpv option group. The hand-written tree splits",
             "        /// Video into fourteen folders because a person did that",
             "        /// splitting; the generated tree cannot, so it stays at one",
             "        /// folder per group rather than pretending to a judgement it",
             "        /// has not made.",
             "        /// </summary>",
             "        private IEnumerable<(string Id, string Caption, string Description, string Icon)>",
             "            GeneratedSections()",
             "        {",
             "            var lang = AppContext.AppLang;",
             "            yield return (nameof(lang.SectionGenVideoRendering), lang.SectionGenVideoRendering, lang.SectionDescGenVideoRendering, \"IconVideo\");",
             "            yield return (nameof(lang.SectionGenColourHdr), lang.SectionGenColourHdr, lang.SectionDescGenColourHdr, \"IconColor\");",
             "            yield return (nameof(lang.SectionGenSubtitles), lang.SectionGenSubtitles, lang.SectionDescGenSubtitles, \"IconSubtitles\");",
             "            yield return (nameof(lang.SectionGenOsd), lang.SectionGenOsd, lang.SectionDescGenOsd, \"IconOsd\");",
             "            yield return (nameof(lang.SectionGenAudio), lang.SectionGenAudio, lang.SectionDescGenAudio, \"IconAudio\");",
             "            yield return (nameof(lang.SectionGenStreaming), lang.SectionGenStreaming, lang.SectionDescGenStreaming, \"IconNetwork\");",
             "            yield return (nameof(lang.SectionGenTracks), lang.SectionGenTracks, lang.SectionDescGenTracks, \"IconPlaylist\");",
             "            yield return (nameof(lang.SectionGenPlayerWindow), lang.SectionGenPlayerWindow, lang.SectionDescGenPlayerWindow, \"IconWindow\");",
             "            yield return (nameof(lang.SectionGenGeneral), lang.SectionGenGeneral, lang.SectionDescGenGeneral, \"IconSettings\");",
             "        }",
             "    }",
             "}",
             ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows, skipped = load_generated()

    print(f"schema entries   : {len(json.loads(SCHEMA.read_text(encoding='utf-8-sig')))}")
    print(f"  deprecated     : {skipped['deprecated']}")
    print(f"  hand-written   : {skipped['hand-written']}")
    print(f"  generated here : {len(rows)}")
    print()
    print("by group:")
    for g, n in Counter(r["group"] for r in rows).most_common():
        print(f"  {n:4d}  {g:22s} -> {GROUP_TO_CATEGORY.get(g, '?')} / {GROUP_TO_SECTION.get(g, '?')}")
    print()
    print("by control type:")
    for t, n in Counter(r["cs"] for r in rows).most_common():
        print(f"  {n:4d}  {t}")
    no_enum_strings = sum(1 for r in rows if r["cs"] == "string" and not r["meta"].get("enum"))
    print(f"  ({no_enum_strings} of the strings are free text; "
          f"{sum(1 for r in rows if r['meta'].get('enum'))} have an enum)")

    targets = {
        SETTINGS / "AppSettings.Gen.cs": gen_appsettings(rows),
        SETTINGS / "MpvSettings.Gen.cs": gen_names(rows),
        SETTINGS / "SettingsPage.Options.Gen.cs": gen_options(rows),
        SETTINGS / "SettingsPage.Sections.Gen.cs": gen_section_glue(rows),
        APP / "Modules" / "Language" / "AppLang.Gen.cs": gen_applang_partial(rows),
        APP / "Modules" / "Language" / "AppLang.Sections.Gen.cs": gen_section_captions(rows),
        GEN_LABELS: json.dumps(gen_labels(rows), ensure_ascii=False, indent=2) + "\n",
    }

    if args.check:
        stale = [p for p, text in targets.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"STALE: {p.relative_to(REPO)}")
        print("OK: generated files up to date" if not stale else f"FAIL: {len(stale)} stale")
        return 1 if stale else 0

    if args.dry_run:
        for p, text in targets.items():
            print(f"  would write {p.relative_to(REPO)}  ({len(text.splitlines())} lines)")
        print("\n--dry-run: nothing written")
        return 0

    for p, text in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        # LF and no BOM, matching the rest of the generated/tooling output.
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(REPO)}  ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
