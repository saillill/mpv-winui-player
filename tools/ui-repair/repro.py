def repro_upstream_fileassoc():
    """Can the user register or remove a file/protocol association from inside the app?

    Upstream ships a settings page for it. The behavioural question is whether any UI
    exists that writes HKCU file associations -- so this looks for the registry write and
    for a settings row that hosts it, under any name.

    **What the first version got wrong, and the rule it produced.** It searched
    `HKEY_CLASSES_ROOT|HKCR:|Shell\\\\Open\\\\Command|Classes\\\\.` plus a `.xaml` whose
    path contains "Association", measured 0 and 0, and would have sent someone to port a
    feature that already works. Three separate probe faults, each measured:

      1. **Doubled backslashes.** The raw string hands git `Classes\\\\.`, i.e. a literal
         backslash then any character. The code writes `Software\\\\Classes\\\\{progId}`.
         `git grep -F 'Software\\\\Classes'` finds `ActivationRegistrationService.cs`
         while the regex finds nothing.
      2. **Case.** The pattern says `Shell\\\\Open\\\\Command`; the source writes
         `shell\\\\open\\\\command`. `git grep -E` is case-sensitive, so the backslash
         would have been the least of it. The same pattern with `-i` does find the file.
      3. **Where the UI lives.** No `.xaml` is named for associations because the row is
         generated by the settings tree, like every other row. Requiring a XAML file with
         "Association" in its path required the feature to be built differently from the
         rest of the page.

    So this now asks the behavioural question with the same two independent measurements
    that refuted the claim, and requires both:

      * a registry writer for file/protocol association, under any name, found without
        hand-escaped paths and without case assumptions; and
      * a settings row that drives it, generated or hand-written.

    **Second fault found by injecting the defect.** The first fix above still passed after
    the row was removed from the tree, because its "settings row" half matched only the
    row's *key* wherever the key appears -- and `SettingsPage.Options.cs` keeps that key in
    the section map, which survives deleting the row. Measured: injecting
    `REMOVED_ASSOC_ROW` over `FileAssociationCheckListKey` in
    `SettingsPage.Options.Program.cs` still reported 3 files and PASS. A probe that passes
    with the feature removed is not evidence, so the wiring half now requires the actual
    call chain -- a checklist row whose apply handler reaches the registration API --
    which is exactly what disappears when the row does.

    Measured 2026-10-24, on the deployed build: 16 video extensions under
    `HKCU\\\\Software\\\\Microsoft\\\\WindowsAppRuntimeApplications\\\\App.3d5842d9062a454b\\\\
    Capabilties\\\\FileAssociations`, `mpvw` and `mpv-winui` under `UrlAssociations`, a
    `...\\\\shell\\\\open\\\\command` on the ProgId, and the row itself in the running
    settings window's UIA tree ("关联媒体文件" / "取消文件关联").
    """
    # Anchored on the CALL, not the API's name anywhere in the file. Measured: the loose
    # version `RegisterForFileTypeActivation|...` still passed after both calls were
    # neutralized, because the same identifiers also appear in the catch-block log line
    # and in the XML doc comment above `EnsureShellCommand`. That is the "ask what the code
    # reads, not what a comment says it does" failure with a concrete cost: the probe was
    # green with the registry writer removed.
    writers = ids(files(r"ActivationRegistrationManager\.RegisterForFileTypeActivation|"
                        r"ActivationRegistrationManager\.RegisterForProtocolActivation",
                        case=False))
    handler = ids(files(r"CheckApplyHandler\s*=\s*_ =>\s*ApplyAssociations\s*\(", case=False))
    # The apply path must reach the registration API, not merely exist beside it: an
    # apply button wired to a local-state write is the dead-code shape this queue catches.
    applies = ids(files(r"Task\s+ApplyAssociationsAsync\s*\(\s*\)", case=False))
    calls = ids(files(r"service\.RegisterAsync\(|\.RegisterAsync\(toRegister\)", case=False))

    print("  registry writers (native API)  %d" % len(writers))
    for p in writers[:6]:
        print("        " + p)
    print("  checklist row + apply handler  %d" % len(handler))
    for p in handler[:6]:
        print("        " + p)
    print("  apply path -> registration     %d / %d" % (len(applies), len(calls)))
    for p in applies[:4]:
        print("        " + p)

    # Both halves are needed: a writer with no row is unreachable from the UI, and a row
    # whose apply button never reaches the writer is the dead-code shape that made the
    # first version of this queue wrong about three other features.
    return bool(writers) and bool(handler) and bool(applies) and bool(calls)


def repro_upstream_appconfdata():
    """Can the app import settings from an external file, from the UI?

    Upstream ships `AppConfData/` (a dialog + 8 KB service + 13 KB of tests). The local
    equivalent is `SettingsPage.Actions.ImportExport.cs`, whose handlers are named
    `ImportConfigAsync` / `ExportConfigAsync`.

    The first version of this reproduction required a file picker and a settings write in
    the SAME file, found 0, and would have sent someone to port a feature that already
    exists. A capability is not a file layout: this now looks for an import entry point
    anywhere, then asks separately whether the pieces line up.
    """
    entry = files(r"ImportConfig|ExportConfig|ImportAppConf|AppConfData")
    picker = files(r"PickSingleFileAsync|PickSaveFileAsync|FileOpenPicker|FileSavePicker")
    both = sorted(set(entry) & set(picker))
    print("  import/export entry points     %d" % len(entry))
    for p in entry[:8]:
        print("        " + p)
    print("  same file also opens a picker  %d" % len(both))
    for p in both[:8]:
        print("        " + p)
    return bool(entry)


def repro_upstream_displayrequest():
    """Does anything keep the display awake while media plays?

    **What the first version got wrong, and the rule it produced.** It searched for
    `DisplayRequest|SetThreadExecutionState|ES_DISPLAY_REQUIRED|ES_CONTINUOUS` in the app's
    own sources, measured 0, and reported "the capability is absent". The capability is
    present: mpv-2.dll imports `SetThreadExecutionState`, `mpv.conf` carries
    `stop-screensaver=yes`, and the live value is `true` during playback. The probe was
    asking whether *this app's* C# spells a Win32 API, which is the same name-match mistake
    as the other three reproductions -- one layer further out.

    Measured 2026-10-24, twice, on the deployed build, with the instrument validated first:

      instrument  `CallNtPowerInformation(SystemExecutionState=16)` read while this process
                  held ES_DISPLAY_REQUIRED on its own thread: 0x1 -> 0x3 -> 0x1. The
                  reading moves, so a zero from it means something.
      idle        app running, nothing loaded          -> 0x1 (ES_SYSTEM_REQUIRED only)
      playing     clip loaded, vo configured, time-pos advancing -> 0x3, i.e.
                  ES_DISPLAY_REQUIRED set: the display is being kept awake.

    Levels 24 (PowerRequestSystemInfo), 0 and 6 return STATUS_ACCESS_DENIED unprivileged and
    8/11/14 want a bigger buffer, so 16 is the only OS reading available here -- which is
    why it is the one used.

    **A source scan cannot answer this question in either direction**, so this reproduction
    no longer pretends to. It reports the three facts that are cheap to read statically --
    the app's default for `stop-screensaver`, the DLL's SetThreadExecutionState import, and
    the option being exposed as a settings row -- and defers the pass/fail to the runtime
    probe recorded in the queue row. A static 0 here was never evidence of absence.

    The default is read from `AppSettings.Gen.cs`, not from `mpv.conf`: the source
    `mpv.conf` has no `stop-screensaver` line at all because `yes` is mpv's own default and
    nothing needs overriding. Searching the config file for it measured 0 and would have
    reproduced the same class of mistake one level down -- the line only appears in
    `%LOCALAPPDATA%\\mpv-winui\\mpv\\mpv.conf`, which ConfigDeployer *generates* from the
    settings, i.e. it is an output of the code this probe is trying to check.
    """
    # (1) the app's default, which is what mpv runs with unless the user changes it.
    default_yes = False
    cfg = os.path.join(APPSRC, "Modules", "Settings", "AppSettings.Gen.cs")
    if os.path.exists(cfg):
        text = open(cfg, encoding="utf-8", errors="replace").read()
        m = re.search(r"nameof\(Mpv_stop_screensaver\),\s*\"([^\"]*)\"", text)
        default_yes = bool(m) and m.group(1).lower() in ("yes", "always")

    # (2) the binary the player embeds, not the app's own C#.
    dll = os.path.join(REPO, "mpv-winui", "libs", "bin", "x64", "mpv-2.dll")
    dll_has = False
    if os.path.exists(dll):
        dll_has = b"SetThreadExecutionState" in open(dll, "rb").read()

    # (3) the app exposes the option, so a user can turn it off.
    exposed = files(r"Mpv_stop_screensaver", case=False)

    print("  default enables inhibition     %s" % ("yes" if default_yes else "NO"))
    print("  mpv-2.dll SetThreadExecutionState  %s" % ("present" if dll_has else "ABSENT"))
    print("  exposed as a setting row       %d" % len(exposed))
    for p in exposed[:4]:
        print("        " + p)
    print("  NOTE: runtime evidence is in the queue row -- ES_DISPLAY_REQUIRED 0x1 -> 0x3")
    print("        during playback, twice, instrument validated first.")

    return default_yes and dll_has and bool(exposed)


def repro_upstream_win32cmdline():
    """Does the app read its own command line (file association passes paths that way)?

    The app is unpackaged, so it can receive `mpvw.exe "some file.mkv"`. The question is
    whether any argument is read at startup, however it is parsed.
    """
    hits = files(r"GetCommandLine|CommandLineToArgv|Environment\.GetCommandLineArgs|"
                 r"e\.Args\b|LaunchActivatedEventArgs")
    return report("command-line readers", hits, bool(hits))


REPROS = {
    "upstream-fileassoc": repro_upstream_fileassoc,
    "upstream-appconfdata": repro_upstream_appconfdata,
    "upstream-displayrequest": repro_upstream_displayrequest,
    "upstream-win32cmdline": repro_upstream_win32cmdline,
}


def main():
    if len(sys.argv) < 2:
        print("usage: repro.py <id>")
        print("\nreproductions available:")
        for k in REPROS:
            print("   " + k)
        return 2

    want = sys.argv[1]
    fn = REPROS.get(want)
    if fn is None:
        print("UNVERIFIED: no reproduction written for %r yet." % want)
        print("Write one in tools/ui-repair/repro.py, record what it measured in")
        print("QUEUE.md, and only then change product code.")
        return 2

    print("repro: %s" % want)
    present = fn()
    print("\n%s" % ("PASS -- the capability is present" if present
                    else "FAIL -- the capability is absent"))
    return 0 if present else 1


if __name__ == "__main__":
    sys.exit(main())
